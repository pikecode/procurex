export function localizedFixtureName(table, code, name) {
  const fixture = /^(?:PXFLOW(?:-|_)|PXACC(?:-|_)|PXRPT(?:-|_)|CONF(?:STORE|SUPA|SUPB|SKU[A-B]|CAT|UNIT|TPL)\d|TERM(?:STORE|SUP|TPL)\d|DIR(?:STORE|SUP|TPL)\d|PRICE(?:STORE|SUP|SKU|CAT|UNIT)\d|ORDER\d|ITFILE(?:OTHER)?\d|ITMEDIA\d)/i.test(code);
  if ((fixture || (table === 'User' && /^it_confirm_(?:purchaser|finance)_\d+$/.test(code))) && chineseNames[name]) return chineseNames[name];
  if (table === 'User' && name === code && /^it_(?:term|direct|file)(?:_supplier|_store|_finance)?_\d+$/.test(code)) {
    const role = code.includes('_supplier_') ? '供应商' : code.includes('_finance_') ? '财务' : code.includes('_store_') ? '门店' : '附件';
    return `${role}测试用户`;
  }
  return name;
}
